/**
 * Returns a studio-isolated packshot from Israeli supermarket CDNs (Shufersal / Rami Levy).
 */
export function getProductPackshot(itemName: string, categoryId: string): string {
  if (ISRAELI_SUPERMARKET_PACKSHOTS[itemName]) {
    return ISRAELI_SUPERMARKET_PACKSHOTS[itemName];
  }
  for (const [key, url] of Object.entries(ISRAELI_SUPERMARKET_PACKSHOTS)) {
    if (itemName.includes(key) || key.includes(itemName)) {
      return url;
    }
  }
  return CATEGORY_PACKSHOTS[categoryId] || CATEGORY_PACKSHOTS.veg_fruit;
}
