export function getItemIcon(name: string, categoryId: string): string {
  if (ITEM_ICONS[name]) return ITEM_ICONS[name];
  for (const [key, icon] of Object.entries(ITEM_ICONS)) {
    if (name.includes(key) || key.includes(name)) return icon;
  }
  return CATEGORY_DEFAULT_ICONS[categoryId] || '🛒';
}
